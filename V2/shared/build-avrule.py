#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
MV-0 · av-rule — build and distribute.

    python3 build-avrule.py            write av-rule.js, inline it into both builds
    python3 build-avrule.py --check    report what would change, write nothing
    python3 build-avrule.py --strip    remove the inlined copies

Source:  V2/shared/av-rule.src.js  (+ _marks.json, the 12 glyph paths)
Output:  V2/shared/av-rule.js       (the readable, complete module)
         V2/Day30/app.html          inlined as <script id="avRule"> before the
                                    first module that needs it (the VAULTS block),
                                    between <!-- AVRULE BEGIN/END --> markers
         V2/DayOne/js/day01.js      inlined at the very top, between
                                    /* AVRULE BEGIN */ … /* AVRULE END */
Verified by hash after writing. Re-run whenever av-rule.src.js changes.
"""
import io, os, sys, json, hashlib

HERE = os.path.dirname(os.path.abspath(__file__))
V2 = os.path.dirname(HERE)
CHECK = '--check' in sys.argv
STRIP = '--strip' in sys.argv

def read(p): return io.open(p, encoding='utf-8').read()
def write(p, t):
    if not CHECK: io.open(p, 'w', encoding='utf-8').write(t)

# 1 · the module
src = read(os.path.join(HERE, 'av-rule.src.js'))
marks = json.load(io.open(os.path.join(HERE, '_marks.json'), encoding='utf-8'))
module = src.replace('__MARKS__', json.dumps(marks, ensure_ascii=False, indent=4))
H = hashlib.sha256(module.encode('utf-8')).hexdigest()[:12]
module = module.replace('av-rule.js · ONE answer', 'av-rule.js (build %s) · ONE answer' % H, 1)
out = os.path.join(HERE, 'av-rule.js')
changed = []
if not os.path.exists(out) or read(out) != module:
    changed.append('shared/av-rule.js'); write(out, module)

# 2 · Day30: <script id="avRule"> before the VAULTS module
HB, HE = '<!-- AVRULE BEGIN - generated by V2/shared/build-avrule.py, do not edit -->\n', '<!-- AVRULE END -->\n'
def html_strip(t):
    i, j = t.find(HB), t.find(HE)
    if i < 0 or j < 0: return t, False
    return t[:i] + t[j + len(HE):], True
def html_add(t):
    # before the Vault's own av-rule stylesheet (MV-1) when it is there, else before the VAULTS block
    anchor = '<style id="avRuleVault">'
    k = t.find(anchor)
    if k < 0:
        anchor = '<!-- ============ VAULTS ============'; k = t.find(anchor)
    assert k > 0, 'Day30 anchor not found'
    blk = HB + '<script id="avRule">\n' + module.rstrip('\n') + '\n</script>\n' + HE
    return t[:k] + blk + t[k:]
p = os.path.join(V2, 'Day30', 'app.html'); t = read(p); base, had = html_strip(t)
new = base if STRIP else html_add(base)
if new != t: changed.append('Day30/app.html (%s)' % ('strip' if STRIP else 'rebuild' if had else 'add')); write(p, new)

# 3 · DayOne: at the top of day01.js
JB, JE = '/* AVRULE BEGIN - generated by V2/shared/build-avrule.py, do not edit */\n', '/* AVRULE END */\n'
def js_strip(t):
    i, j = t.find(JB), t.find(JE)
    if i < 0 or j < 0: return t, False
    return t[:i] + t[j + len(JE):], True
def js_add(t): return JB + module.rstrip('\n') + '\n' + JE + t
p = os.path.join(V2, 'DayOne', 'js', 'day01.js'); t = read(p); base, had = js_strip(t)
new = base if STRIP else js_add(base)
if new != t: changed.append('DayOne/js/day01.js (%s)' % ('strip' if STRIP else 'rebuild' if had else 'add')); write(p, new)

# 4 · verify by hash (what is in the files is what the source says)
if not STRIP and not CHECK:
    for rel, b, e in [('Day30/app.html', '<script id="avRule">\n', '\n</script>\n' + HE),
                      ('DayOne/js/day01.js', JB, '\n' + JE)]:
        t = read(os.path.join(V2, rel)); i = t.find(b) + len(b); j = t.find(e, i)
        got = hashlib.sha256(t[i:j].encode('utf-8')).hexdigest()[:12]
        want = hashlib.sha256(module.rstrip('\n').encode('utf-8')).hexdigest()[:12]
        print('  %-20s %s %s' % (rel, got, 'ok' if got == want else 'MISMATCH'))
print(('CHECK ONLY - would change: ' if CHECK else 'changed: ') + (', '.join(changed) if changed else 'nothing'))
print('build', H)
